"""Audit exact credential-free single-file releases; optionally scan Git history."""
import argparse
import hashlib
import json
import mmap
from pathlib import Path
import re
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--release-dir', type=Path, default=ROOT/'dist')
parser.add_argument('--history', action='store_true')
args = parser.parse_args()
DIST = args.release_dir.resolve()
markers = []
def collect(value):
    if isinstance(value, dict):
        for key, item in value.items():
            if any(word in key.lower() for word in ('apikey','api_key','password','token','access','refresh')) and isinstance(item,str) and len(item)>16:
                markers.append(item.encode())
            elif key.lower()=='key' and isinstance(item,str) and len(item)>16:
                markers.append(item.encode())
            else: collect(item)
    elif isinstance(value,list):
        for item in value: collect(item)
for source in [ROOT/'private/pi.config.json', Path.home()/'.pi/agent/auth.json']:
    if source.exists(): collect(json.loads(source.read_text(encoding='utf-8-sig')))
patterns = [re.compile(rb'gh[opusr]_[A-Za-z0-9]{25,}'), re.compile(rb'sk-[A-Za-z0-9_-]{32,}'),
            re.compile(rb'AKIA[A-Z0-9]{16}'), re.compile(rb'npm_[A-Za-z0-9]{30,}')]
def no_private_key(data):
    assert all(marker not in data for marker in markers), 'Private credential found; publication refused'

manifest = json.loads((DIST/'manifest.json').read_text())
assert manifest['credentialFree'] is True
for record in manifest['artifacts']:
    assert hashlib.sha256((DIST/record['file']).read_bytes()).hexdigest()==record['sha256']
for platform, binary in [('windows','pi-windows-x64.exe'),('linux','pi-linux-x64')]:
    payload_path = ROOT/'.build'/('payload-'+platform+'.zip')
    payload = payload_path.read_bytes()
    record = next(x for x in manifest['artifacts'] if x['file']==binary)
    assert hashlib.sha256(payload).hexdigest()==record['payloadSha256']
    with (DIST/binary).open('rb') as file, mmap.mmap(file.fileno(),0,access=mmap.ACCESS_READ) as mapped:
        assert mapped.find(payload)>=0, 'Executable does not embed the audited runtime'
    with zipfile.ZipFile(payload_path) as bundle:
        assert json.loads(bundle.read('provision/auth.json'))=={}
        assert json.loads(bundle.read('defaults/config.json'))['apiKey']==''
        assert 'provision/extensions/solomux.ts' in bundle.namelist()
        assert 'licenses/Pi-LICENSE.txt' in bundle.namelist()
        for item in bundle.infolist(): no_private_key(bundle.read(item))
    for name in ('README.zh-CN.md','README.en.md'):
        no_private_key((DIST/name).read_bytes())

blobs = 0
if args.history:
    objects = subprocess.check_output(['git','rev-list','--objects','--all'],cwd=ROOT).splitlines()
    batch = subprocess.Popen(['git','cat-file','--batch'],cwd=ROOT,stdin=subprocess.PIPE,stdout=subprocess.PIPE)
    try:
        for line in objects:
            oid = line.split(b' ',1)[0]
            batch.stdin.write(oid+b'\n'); batch.stdin.flush()
            header=batch.stdout.readline().split()
            data=batch.stdout.read(int(header[2])); batch.stdout.read(1)
            if header[1]==b'blob':
                blobs += 1; no_private_key(data)
                assert not any(p.search(data) for p in patterns), 'Potential credential in Git history; publication refused'
    finally:
        batch.stdin.close(); batch.stdout.close(); batch.wait()
    for filename in subprocess.check_output(['git','ls-files','-z'],cwd=ROOT).split(b'\0'):
        if filename:
            path=ROOT/filename.decode()
            if path.exists():
                data=path.read_bytes(); no_private_key(data)
                assert not any(p.search(data) for p in patterns), 'Potential credential in working source; publication refused'
report={'credentialFree':True,'autoGeneratedConfigKeyBlank':True,'bothEmbeddedPayloadsInspected':True,
        'privateCredentialScanPassed':True,'gitHistoryBlobsScanned':blobs,
        'bilingualReadmesPresent':True,'upstreamLicenseIncluded':True}
(DIST/'release-audit.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
